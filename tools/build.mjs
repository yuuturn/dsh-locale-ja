/**
 * Build `lib/client.js` from the per-namespace dictionaries in `locale/ja/`.
 *
 * The DSH client module system serves *built* client bundles: each shipped
 * `lib/client.js` is a `window.__ModuleLoader__.load({ id, factory })` wrapper
 * whose factory returns the plugin's exports. This package ships no bundler
 * (the pack is data plus a few registration calls), so this script emits that
 * wrapper directly.
 *
 * Usage: node tools/build.mjs [--check]
 *   --check  exit non-zero when lib/client.js is out of date instead of writing
 */

import { readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const dictDir = join(root, 'locale', 'ja')
const target = join(root, 'lib', 'client.js')
const packageName = 'dsh-locale-ja'
const language = { id: 'ja', label: '日本語', fallback: 'en' }

/** Namespaces whose dictionaries ship in this pack, read from `locale/ja/`. */
async function readDictionaries() {
  const names = (await readdir(dictDir))
    .filter((name) => name.endsWith('.json') && !name.startsWith('_'))
    .sort()
  const dictionaries = {}
  for (const name of names) {
    const namespace = name.slice(0, -'.json'.length)
    const text = await readFile(join(dictDir, name), 'utf8')
    const entries = JSON.parse(text)
    if (typeof entries !== 'object' || entries === null || Array.isArray(entries)) {
      throw new Error(`build: locale/ja/${name} must contain a JSON object`)
    }
    dictionaries[namespace] = entries
  }
  return dictionaries
}

/** Render the loader wrapper served to the browser. */
function render(dictionaries, fontCss) {
  // `common` first: every other namespace falls back to it.
  const namespaces = Object.keys(dictionaries).sort((a, b) =>
    a === 'common' ? -1 : b === 'common' ? 1 : a.localeCompare(b),
  )

  const dictLines = []
  for (const namespace of namespaces) {
    const json = JSON.stringify(dictionaries[namespace], null, '\t').split('\n')
    dictLines.push(`\t\t\t${JSON.stringify(namespace)}: ${json[0]}`)
    for (const line of json.slice(1, -1)) dictLines.push(`\t\t\t${line}`)
    dictLines.push(`\t\t\t${json[json.length - 1]},`)
  }

  const fontRuntime = fontCss === undefined ? '' : `
		/**
		 * Stylesheet re-pointing the theme's font variables while the document is
		 * Japanese (see locale/ja/font.css for why the shipped stack needs it).
		 */
		const FONT_CSS = ${JSON.stringify(fontCss)};

		/** \`data-plugin-css\` marker that makes the injection idempotent. */
		const FONT_CSS_ID = ${JSON.stringify(`${packageName}/font.css`)};

		/**
		 * Append this pack's stylesheet once, following the shipped client-plugin
		 * CSS convention so a second activation cannot duplicate it.
		 * @returns a disposer that removes the style tag.
		 */
		function applyFontOverride() {
			if (typeof document === "undefined" || document.head === undefined) return () => {};
			if (document.querySelector("style[data-plugin-css=" + JSON.stringify(FONT_CSS_ID) + "]") !== null) return () => {};
			const tag = document.createElement("style");
			tag.dataset.plugin = ${JSON.stringify(packageName)};
			tag.dataset.pluginCss = FONT_CSS_ID;
			tag.textContent = FONT_CSS;
			document.head.appendChild(tag);
			return () => { tag.remove(); };
		}
`

  const fontApply = fontCss === undefined
    ? ''
    : `\t\t\tctx.effect(() => applyFontOverride(), "locale-ja: Japanese font override");\n`

  const fontExports = fontCss === undefined
    ? ''
    : `\t\texports.FONT_CSS = FONT_CSS;
\t\texports.applyFontOverride = applyFontOverride;
`

  return `// Generated by tools/build.mjs from locale/ja/*.json and locale/ja/font.css — do not edit by hand.
//
// Japanese language pack for the DSH web GUI: registers the \`ja\` language, one
// dictionary per namespace, and a Japanese-first font override. Keys missing
// here fall back to \`en\` through the locale service's fallback chain.
window.__ModuleLoader__.load({
	id: ${JSON.stringify(packageName)},
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
		Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

		/** Language definition registered with the locale service. */
		const LANGUAGE = Object.freeze(${JSON.stringify(language)});

		/** Namespace dictionaries for \`ja\`, keyed by locale namespace. */
		const DICTIONARIES = {
${dictLines.join('\n')}
		};
${fontRuntime}
		const inject = ["locale"];

		/**
		 * Register the language, every dictionary, and the font override with the
		 * locale service.
		 * @param ctx - client cordis context carrying the \`locale\` service.
		 */
		function apply(ctx) {
			ctx.effect(() => ctx.locale.addLanguage(LANGUAGE), "locale-ja: language");
			for (const namespace of Object.keys(DICTIONARIES)) {
				ctx.effect(
					() => ctx.locale.register(namespace, LANGUAGE.id, DICTIONARIES[namespace]),
					\`locale-ja: \${namespace} dictionary\`,
				);
			}
${fontApply}\t\t}

		exports.LANGUAGE = LANGUAGE;
		exports.DICTIONARIES = DICTIONARIES;
${fontExports}\t\texports.apply = apply;
		exports.inject = inject;
		return module.exports;
	}
});
`
}

/**
 * The font stylesheet injected while the document is Japanese.
 *
 * `locale/ja/font.css` is the source of truth — including its explanatory
 * comment, which stays in the repository rather than in the served bundle.
 * Deleting the file ships no font override.
 */
async function readFontCss() {
  try {
    const text = (await readFile(join(dictDir, 'font.css'), 'utf8')).trim()
    const css = text.replace(/\/\*[\s\S]*?\*\//g, '').trim()
    return css.length > 0 ? css : undefined
  } catch (error) {
    if (error.code === 'ENOENT') return undefined
    throw error
  }
}

const dictionaries = await readDictionaries()
const fontCss = await readFontCss()
const source = render(dictionaries, fontCss)
const check = process.argv.includes('--check')

let current
try {
  current = await readFile(target, 'utf8')
} catch {
  current = undefined
}

if (current === source) {
  console.log(`build: lib/client.js is up to date (${Object.keys(dictionaries).length} namespaces)`)
} else if (check) {
  console.error('build: lib/client.js is out of date; run `node tools/build.mjs`')
  process.exitCode = 1
} else {
  await writeFile(target, source)
  const keys = Object.values(dictionaries).reduce((total, dict) => total + Object.keys(dict).length, 0)
  console.log(
    `build: wrote lib/client.js (${Object.keys(dictionaries).length} namespaces, ${keys} keys)`,
  )
}
